// Regenerates src/abi/generated/*.ts from Foundry artifacts in ../contracts/out.
// Usage: npm run abi:sync   (run `forge build` in contracts/ first)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../contracts/out');
const dest = resolve(here, '../src/abi/generated');
const contracts = { MachineVault: 'machineVault', GachaForgeFactory: 'gachaForgeFactory', BuybackBurner: 'buybackBurner' };

for (const [name, ident] of Object.entries(contracts)) {
  const file = resolve(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    console.warn(`skip ${name}: ${file} not found`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(file, 'utf8'));
  const src = `// AUTO-GENERATED by scripts/sync-abi.mjs from contracts/out/${name}.sol/${name}.json — do not edit.\nexport const ${ident}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(resolve(dest, `${ident}.ts`), src);
  console.log(`wrote ${ident}.ts (${abi.length} entries)`);
}
